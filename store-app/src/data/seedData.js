export function buildSeedOrders() {
  const orders = [];
  let current = null;
  let orderCounter = 1;

  for (const [id, barcode, name, price, qty, soldAt] of SEED_SALES) {
    const ts = new Date(soldAt).getTime();
    const costPrice = Math.round(price * 0.75 * 100) / 100;
    const item = {
      id,
      barcode,
      name,
      price,
      cost_price: costPrice,
      qty,
      sold_at: soldAt,
    };

    if (current && Math.abs(ts - current._ts) <= 3000) {
      current.items.push(item);
      current.total_amount += price * qty;
      current.total_cost += costPrice * qty;
      current.total_items += qty;
      current.cash_received = current.total_amount;
    } else {
      current = {
        id: `seed-order-${orderCounter}`,
        order_no: orderCounter,
        cashier_id: 'local-owner-1',
        cashier_name: 'เจ้าของร้าน (ข้อมูลเดิม)',
        total_amount: price * qty,
        total_cost: costPrice * qty,
        total_items: qty,
        payment_method: 'cash',
        cash_received: price * qty,
        change_given: 0,
        status: 'completed',
        sold_at: soldAt,
        items: [item],
        _ts: ts,
      };
      orders.push(current);
      orderCounter += 1;
    }
  }

  return orders.map(({ _ts, ...rest }) => rest).reverse();
}
